from __future__ import annotations

from copy import deepcopy
from typing import Any, Dict, Iterable, List
from pathlib import Path
import hashlib
import re
import subprocess

from research.research_os.scientific_store import sha256_json


ALLOWED_DATA_CLASSES = {
    "REGULATORY_FILINGS",
    "CORPORATE_IR",
    "OFFICIAL_MACRO",
    "EXCHANGE_REFERENCE",
    "PUBLIC_INDEX_RULES",
    "OFFICIAL_CORPORATE_ACTIONS",
}
ALLOWED_ACTIVATION_STATES = {"DESIGN_ONLY_NOT_CONNECTED", "FIXTURE_ONLY"}


APPLE_FY2025_STATEMENTS = 'https://www.apple.com/newsroom/pdfs/fy2025-q4/FY25_Q4_Consolidated_Financial_Statements.pdf'


def capture_apple_statement_cells(pdf_path: Path, *, retrieved_at: str) -> Dict[str, Any]:
    """Extract one qualified accounting basis from an already-downloaded PDF.

    No network, price series, future observations or scheduled acquisition. This
    provider-specific parser refuses unfamiliar layouts rather than guessing.
    """
    from .engine_dossiers_v1 import _clock
    _clock(retrieved_at)
    pdf_path = Path(pdf_path)
    raw = pdf_path.read_bytes()
    if not raw.startswith(b'%PDF-'):
        raise ValueError('expected original PDF bytes')
    text = subprocess.check_output(['pdftotext', '-layout', str(pdf_path), '-'], text=True)
    pages = text.split('\f')
    if len(pages) < 3:
        raise ValueError('financial statement pages missing')
    for page in (pages[0], pages[2]):
        if not all(s in page for s in ('Twelve Months Ended', 'September 27,', '2025', '2024', 'In millions')):
            raise ValueError('unqualified statement period or units')
    selectors = {
        'revenue':(0, 'Total net sales', 4, 2),
        'operating_income':(0, 'Operating income', 4, 2),
        'operating_cash_flow':(2, 'Cash generated by operating activities', 2, 0),
        'capital_expenditure':(2, 'Payments for acquisition of property, plant and equipment', 2, 0),
    }
    facts, spans, rows = {}, {}, []
    for key, (page_index, label, count, column) in selectors.items():
        lines = pages[page_index].splitlines()
        index = next((i for i, line in enumerate(lines) if label in line), None)
        if index is None:
            raise ValueError('required financial statement row missing')
        row = lines[index].split(label, 1)[1]
        values = re.findall(r'\(?-?\d[\d,]*(?:\.\d+)?\)?', row)
        if len(values) < count and index + 1 < len(lines):
            values = re.findall(r'\(?-?\d[\d,]*(?:\.\d+)?\)?', row + ' ' + lines[index + 1])
        if len(values) != count and not (key == 'revenue' and len(values) == count + 1):
            raise ValueError('ambiguous statement columns')
        literal = values[-count:][column].replace(',', '').replace('(', '-').replace(')', '')
        value = abs(int(literal)) if key == 'capital_expenditure' else int(literal)
        offset = len(''.join(rows)) + len(key) + 1
        rows.append(f'{key}={literal}\n')
        spans[key] = {'start':offset, 'end':offset + len(literal), 'page':page_index + 1,
                      'column':'FY2025_TWELVE_MONTHS',
                      'normalization':'OUTFLOW_MAGNITUDE' if key == 'capital_expenditure' else 'AS_REPORTED'}
        facts[key] = str(value)
    numeric_text = ''.join(rows)
    packet = {
        'evidence_class':'DOCUMENTARY', 'source_ref':APPLE_FY2025_STATEMENTS,
        'issuer_id':'AAPL', 'published_at':retrieved_at, 'available_at':retrieved_at,
        'revision_status':'CAPTURED_VERSION_AS_OF_RETRIEVAL', 'period':'FY2025_TWELVE_MONTHS_ENDED_2025-09-27',
        'unit':'USD_millions', 'facts':facts,
        'capture':{'source_url':APPLE_FY2025_STATEMENTS, 'retrieved_at':retrieved_at,
                   'publication_clock_basis':'FIRST_VERIFIED_PUBLIC_CAPTURE_NOT_HISTORICAL_PIT',
                   'raw_sha256':hashlib.sha256(raw).hexdigest(), 'representation':'NUMERIC_CELLS',
                   'extractor':'apple-statement-cells.v1/pdftotext-layout', 'period':'FY2025_TWELVE_MONTHS_ENDED_2025-09-27',
                   'unit':'USD_millions', 'text':numeric_text, 'text_sha256':hashlib.sha256(numeric_text.encode()).hexdigest(),
                   'fact_spans':spans},
    }
    packet['content_hash'] = sha256_json(packet)
    return {'source_ref':APPLE_FY2025_STATEMENTS, 'freeze_time':retrieved_at, 'documentary_packet':packet}


def validate_adapter_spec(spec: Dict[str, Any]) -> Dict[str, Any]:
    blockers: List[str] = []
    required = {
        "adapter_id",
        "provider_family",
        "data_class",
        "permission_model",
        "clock_semantics",
        "revision_policy",
        "survivorship_policy",
        "locator_template",
        "activation_state",
        "network_access",
        "contains_market_outcome",
    }
    for field in sorted(required - spec.keys()):
        blockers.append(f"MISSING_{field.upper()}")
    if spec.get("data_class") not in ALLOWED_DATA_CLASSES:
        blockers.append("DATA_CLASS_NOT_ALLOWED")
    if spec.get("activation_state") not in ALLOWED_ACTIVATION_STATES:
        blockers.append("ACTIVATION_STATE_NOT_ALLOWED")
    if spec.get("network_access") is not False:
        blockers.append("NETWORK_ACCESS_FORBIDDEN_IN_WAVE3")
    if spec.get("contains_market_outcome") is not False:
        blockers.append("OUTCOME_BEARING_ADAPTER_FORBIDDEN")
    for field in ("permission_model", "clock_semantics", "revision_policy", "survivorship_policy", "locator_template"):
        if spec.get(field) in (None, "", "UNKNOWN"):
            blockers.append(f"{field.upper()}_UNKNOWN")

    canonical = {
        "adapter_id": spec.get("adapter_id"),
        "provider_family": spec.get("provider_family"),
        "data_class": spec.get("data_class"),
        "permission_model": spec.get("permission_model"),
        "clock_semantics": spec.get("clock_semantics"),
        "revision_policy": spec.get("revision_policy"),
        "survivorship_policy": spec.get("survivorship_policy"),
        "locator_template": spec.get("locator_template"),
        "activation_state": spec.get("activation_state"),
        "network_access": spec.get("network_access"),
        "contains_market_outcome": spec.get("contains_market_outcome"),
        "allowed_content": sorted(spec.get("allowed_content") or []),
        "forbidden_content": sorted(spec.get("forbidden_content") or []),
    }
    return {
        "adapter_id": spec.get("adapter_id"),
        "status": "PASS" if not blockers else "BLOCK",
        "blockers": sorted(set(blockers)),
        "adapter_hash": sha256_json(canonical),
        "canonical_spec": canonical,
        "network_access": False,
        "outcome_access_authorized": False,
        "activated": False,
    }


class DesignOnlyAdapterRegistry:
    def __init__(self) -> None:
        self._entries: Dict[str, Dict[str, Any]] = {}

    def register(self, validated: Dict[str, Any]) -> Dict[str, Any]:
        adapter_id = validated.get("adapter_id")
        if not adapter_id:
            raise ValueError("adapter_id required")
        current = self._entries.get(adapter_id)
        if current is not None:
            if current["adapter_hash"] != validated["adapter_hash"]:
                raise ValueError(f"adapter mutation rejected: {adapter_id}")
            return deepcopy(current)
        self._entries[adapter_id] = deepcopy(validated)
        return deepcopy(validated)

    def register_many(self, records: Iterable[Dict[str, Any]]) -> None:
        for record in records:
            self.register(record)

    def snapshot(self) -> Dict[str, Any]:
        entries = [deepcopy(self._entries[key]) for key in sorted(self._entries)]
        return {
            "registry_id": "design-only-source-adapters.v1",
            "entry_count": len(entries),
            "entries": entries,
            "activated_count": sum(bool(item["activated"]) for item in entries),
            "network_enabled_count": sum(bool(item["network_access"]) for item in entries),
            "outcome_authorized_count": sum(bool(item["outcome_access_authorized"]) for item in entries),
            "immutable": True,
        }
