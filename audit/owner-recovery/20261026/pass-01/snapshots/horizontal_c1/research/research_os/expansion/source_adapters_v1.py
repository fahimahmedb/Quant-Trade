def capture_sec_t1_rule(xml_path: Path, *, retrieved_at: str) -> Dict[str, Any]:
    import xml.etree.ElementTree as ET
    raw = Path(xml_path).read_bytes()
    root = ET.fromstring(raw)
    if root.findtext('./FDSYS/DATE') != '2025-04-01' or root.findtext('.//SECTION/SUBJECT') != 'Settlement cycle.':
        raise ValueError('unqualified CFR edition or section')
    section_text = '\n'.join(' '.join(''.join(p.itertext()).split()) for p in root.findall('.//SECTION/P'))
    packet = sec_t1_rule_packet({
        'source_url':SEC_T1_RULE, 'raw_sha256':hashlib.sha256(raw).hexdigest(), 'retrieved_at':retrieved_at,
        'publication_clock_basis':'FIRST_VERIFIED_PUBLIC_CAPTURE_NOT_HISTORICAL_PIT',
        'document_kind':'OFFICIAL_CFR_OPERATIVE_RULE_EDITION', 'edition_date':'2025-04-01',
        'section':'17 CFR 240.15c6-1', 'section_text':section_text, 'extractor':'govinfo-cfr-15c6-1.v1',
    })
    return {'source_ref':SEC_T1_RULE, 'freeze_time':retrieved_at, 'documentary_packet':packet}


def assess_t1_rule_scope(transaction: Dict[str, Any]) -> Dict[str, Any]:
    """Conservative rule-scope logic for explicit assumptions, not a legal opinion.

    No caller scenario is evidence of an actual covered trade or forced flow.
    Unknown exception flags prevent positive eligibility.
    """
    flags = {'broker_or_dealer', 'agreed_alternate_date', 'commission_exemption', 'firm_commitment_offering'}
    if set(transaction) != flags | {'security_class'}:
        return {'status':'UNKNOWN', 'reason':'SCOPE_PREMISES_MISSING'}
    if transaction['broker_or_dealer'] is False:
        return {'status':'OUTSIDE_BOUNDED_SCOPE', 'reason':'ACTOR_OUTSIDE_SCOPE'}
    if any(transaction[k] is True for k in flags - {'broker_or_dealer'}):
        return {'status':'OUTSIDE_BOUNDED_SCOPE', 'reason':'EXCEPTION_OR_ALTERNATE_DATE'}
    excluded = {'EXEMPTED_SECURITY', 'GOVERNMENT_SECURITY', 'MUNICIPAL_SECURITY', 'COMMERCIAL_PAPER',
                'BANKERS_ACCEPTANCE', 'COMMERCIAL_BILL', 'UNLISTED_LIMITED_PARTNERSHIP', 'SECURITY_BASED_SWAP'}
    if not isinstance(transaction['security_class'], str):
        return {'status':'UNKNOWN', 'reason':'SCOPE_PREMISES_UNQUALIFIED'}
    if transaction['security_class'] in excluded:
        return {'status':'OUTSIDE_BOUNDED_SCOPE', 'reason':'EXCLUDED_INSTRUMENT'}
    if any(type(transaction[k]) is not bool for k in flags) or transaction['security_class'] != 'ORDINARY_COMMON_EQUITY':
        return {'status':'UNKNOWN', 'reason':'SCOPE_PREMISES_UNQUALIFIED'}
    return {'status':'CONDITIONALLY_WITHIN_RULE_SCOPE', 'reason':'DECLARED_ASSUMPTIONS_ONLY_NOT_ACTUAL_TRANSACTION_EVIDENCE'}


def validate_adapter_spec(spec: Dict[str, Any]) -> Dict[str, Any]:
    blockers: List[str] = []
    required = {
        "adapter_id",
        "provider_family",
        "data_class",
        "permission_model",
        "clock_semantics",
        "revision_policy",
        "survivorship_policy",
        "locator_template",
        "activation_state",
        "network_access",
        "contains_market_outcome",
    }
    for field in sorted(required - spec.keys()):
        blockers.append(f"MISSING_{field.upper()}")
    if spec.get("data_class") not in ALLOWED_DATA_CLASSES:
        blockers.append("DATA_CLASS_NOT_ALLOWED")
    if spec.get("activation_state") not in ALLOWED_ACTIVATION_STATES:
        blockers.append("ACTIVATION_STATE_NOT_ALLOWED")
    if spec.get("network_access") is not False:
        blockers.append("NETWORK_ACCESS_FORBIDDEN_IN_WAVE3")
    if spec.get("contains_market_outcome") is not False:
        blockers.append("OUTCOME_BEARING_ADAPTER_FORBIDDEN")
    for field in ("permission_model", "clock_semantics", "revision_policy", "survivorship_policy", "locator_template"):
        if spec.get(field) in (None, "", "UNKNOWN"):
            blockers.append(f"{field.upper()}_UNKNOWN")

    canonical = {
        "adapter_id": spec.get("adapter_id"),
        "provider_family": spec.get("provider_family"),
        "data_class": spec.get("data_class"),
        "permission_model": spec.get("permission_model"),
        "clock_semantics": spec.get("clock_semantics"),
        "revision_policy": spec.get("revision_policy"),
        "survivorship_policy": spec.get("survivorship_policy"),
        "locator_template": spec.get("locator_template"),
        "activation_state": spec.get("activation_state"),
        "network_access": spec.get("network_access"),
        "contains_market_outcome": spec.get("contains_market_outcome"),
        "allowed_content": sorted(spec.get("allowed_content") or []),
        "forbidden_content": sorted(spec.get("forbidden_content") or []),
    }
    return {
        "adapter_id": spec.get("adapter_id"),
        "status": "PASS" if not blockers else "BLOCK",
        "blockers": sorted(set(blockers)),
        "adapter_hash": sha256_json(canonical),
        "canonical_spec": canonical,
        "network_access": False,
        "outcome_access_authorized": False,
        "activated": False,
    }


class DesignOnlyAdapterRegistry:
    def __init__(self) -> None:
        self._entries: Dict[str, Dict[str, Any]] = {}

    def register(self, validated: Dict[str, Any]) -> Dict[str, Any]:
        adapter_id = validated.get("adapter_id")
        if not adapter_id:
            raise ValueError("adapter_id required")
        current = self._entries.get(adapter_id)
        if current is not None:
            if current["adapter_hash"] != validated["adapter_hash"]:
                raise ValueError(f"adapter mutation rejected: {adapter_id}")
            return deepcopy(current)
        self._entries[adapter_id] = deepcopy(validated)
        return deepcopy(validated)

    def register_many(self, records: Iterable[Dict[str, Any]]) -> None:
        for record in records:
            self.register(record)

    def snapshot(self) -> Dict[str, Any]:
        entries = [deepcopy(self._entries[key]) for key in sorted(self._entries)]
        return {
            "registry_id": "design-only-source-adapters.v1",
            "entry_count": len(entries),
            "entries": entries,
            "activated_count": sum(bool(item["activated"]) for item in entries),
            "network_enabled_count": sum(bool(item["network_access"]) for item in entries),
            "outcome_authorized_count": sum(bool(item["outcome_access_authorized"]) for item in entries),
            "immutable": True,
        }
