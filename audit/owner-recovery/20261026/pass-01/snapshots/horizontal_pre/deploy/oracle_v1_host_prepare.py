BRANCH = 'builder/oracle-economic-loop-recovery-20261019'
VM = 'ocid1.instance.oc1.eu-paris-1.anrwiljrtoradqacmugziwzu3sls2orieua6i7vkjveiq7q5wsiypa3mejpa'
