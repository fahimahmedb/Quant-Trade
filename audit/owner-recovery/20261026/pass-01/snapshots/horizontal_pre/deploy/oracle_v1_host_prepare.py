def checked(argv, *, timeout=180):
    return subprocess.run(argv, capture_output=True, text=True, timeout=timeout, check=True).stdout.strip()


def write_atomic(path, data, mode=0o644, *, uid=0, gid=0):
    fd, pending = tempfile.mkstemp(prefix='.quant-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.chown(pending, uid, gid)
        os.chmod(pending, mode)
        os.replace(pending, path)
    finally:
        if os.path.exists(pending):
            os.unlink(pending)


def copy_verified(source, target, spec, verify, *, magic=None):
    target.parent.mkdir(parents=True, exist_ok=True, mode=0o755)
    if target.exists() or target.is_symlink():
        verify(target, spec, magic=magic)
        return
    fd, pending = tempfile.mkstemp(prefix='.asset-', dir=target.parent)
    try:
        with os.fdopen(fd, 'wb') as out:
            source_fd = os.open(source, os.O_RDONLY | os.O_NOFOLLOW)
            with os.fdopen(source_fd, 'rb') as incoming:
                if not stat.S_ISREG(os.fstat(incoming.fileno()).st_mode):
                    raise ValueError('ASSET_SOURCE_MUST_BE_REGULAR')
                shutil.copyfileobj(incoming, out, 8 * 1024 * 1024)
                out.flush()
                os.fsync(out.fileno())
        verify(Path(pending), spec, magic=magic)
        os.chmod(pending, 0o644)
        os.replace(pending, target)
    finally:
        if os.path.exists(pending):
            os.unlink(pending)


def verify_local_qualification(report, runtime, model, policy_hash):
    if (report.get('status') != 'PASS_LOCAL_COMMENTARY_BACKEND_ONLY'
            or report.get('temporary_server_stopped') is not True
            or report.get('github_writes') != 0 or report.get('hosted_model_calls') != 0):
        raise ValueError('ACTUAL_LOCAL_BACKEND_QUALIFICATION_REQUIRED')
    for name, spec in (('runtime', runtime), ('model', model)):
        if (report.get('assets', {}).get(name) or {}).get('sha256') != spec['sha256']:
            raise ValueError('LOCAL_QUALIFICATION_ASSET_MISMATCH')
    cases = report.get('scientific_cases', [])
    expected = {'closed_authority', 'unresolved_overlap', 'missing_correlation', 'independent_validation',
                'proved_distinct_structural_screen'}
    if {case.get('case') for case in cases} != expected or len(cases) != len(expected) or any(case.get('passed') is not True for case in cases):
        raise ValueError('LOCAL_QUALIFICATION_SCIENTIFIC_CASES_MISSING')
    if report.get('reasoning_policy_hash') != policy_hash:
        raise ValueError('LOCAL_QUALIFICATION_PRODUCTION_POLICY_MISMATCH')
    when = datetime.fromisoformat(report['completed_at'])
    if when.tzinfo is None or not timedelta(0) <= datetime.now(timezone.utc) - when <= timedelta(hours=6):
        raise ValueError('LOCAL_BACKEND_QUALIFICATION_EXPIRED')


def wrapper(release, module, arguments, *, service_user=False):
    # All paths/arguments are generated by this installer, never supplied by a
    # caller of the sudo command. Reject options and preserve a clean environment.
    import shlex
    home = '/var/lib/quant-research' if service_user else '/root'
    command = ['/usr/bin/env', '-i', 'PATH=/usr/bin:/bin', 'HOME=' + home,
               'GIT_TERMINAL_PROMPT=0', '/usr/bin/python3.12', '-B', '-s', '-E', '-m', module, *arguments]
    return ('#!/bin/sh\n[ "$#" -eq 0 ] || exit 64\ncd ' + shlex.quote(str(release)) + '\nexec '
            + shlex.join(command) + '\n').encode()


def bootstrap(sha):
    if not re.fullmatch('[0-9a-f]{40}', sha):
        raise ValueError('EXACT_COMMIT_SHA_REQUIRED')
    url = f'https://raw.githubusercontent.com/{REPOSITORY}/{sha}/deploy/oracle_release_install.py'
    with urllib.request.urlopen(url, timeout=30) as response:
        source = response.read(131073)
    if len(source) > 131072 or hashlib.sha256(source).hexdigest() != INSTALLER_SHA256:
        raise ValueError('VERSIONED_CP1_INSTALLER_HASH_MISMATCH')
    namespace = {'__name__': 'qualified_bootstrap', '__file__': url}
    exec(compile(source, url, 'exec'), namespace)
    return namespace['install_release'](sha, base=Path('/opt/quant-research/releases'))


def prepare(sha, ci_run):
    if os.geteuid() != 0:
        raise ValueError('ROOT_REQUIRED_FOR_HOST_PREPARATION')
    if ci_run <= 0:
        raise ValueError('EXACT_SUCCESSFUL_CI_RUN_REQUIRED')
    receipt = bootstrap(sha)
    release = Path(receipt['path'])
    import sys
    sys.path.insert(0, str(release))
    from deploy.oracle_h24_canary import instance_identity, release_ci
    from deploy.oracle_local_backend_install import RUNTIME, MODEL, stage, verify
    from deploy.oracle_local_backend_qualify import server_command
    from deploy.oracle_scheduler_install import prepare as prepare_worker
    from research.research_os.worker_stages import REASONING_POLICY
    from research.research_os.worker_preflight import canonical_hash

    instance_identity(VM)
    release_ci({'qualification_ci_run_id': ci_run, 'release_sha': sha})
    build_home = Path('/var/lib/ocarun')
    qualification = json.loads((build_home / '.cache/quant-qualification/local-backend.json').read_text())
    verify_local_qualification(qualification, RUNTIME, MODEL, canonical_hash(REASONING_POLICY))

    config = {'repository': REPOSITORY, 'branch': BRANCH, 'release_sha': sha,
              'qualification_ci_run_id': ci_run, 'cache': '/var/lib/quant-research/github.git',
              'worker_id': 'oracle-research-v1', 'lane': 'auto', 'vm_ocid': VM,
              'model_backend': {'implementation': 'gpt_oss', 'runtime': 'openai_compatible',
                                'endpoint': 'http://127.0.0.1:8080', 'model': MODEL['local_alias'],
                                'budget': {'timeout_seconds': 240, 'retries': 0, 'context_tokens': 8192,
                                           'output_tokens': 768, 'temperature': 0, 'seed': 19}}}
    prepare_worker(release, config)
    worker = pwd.getpwnam('quant-research')
    try:
        model_user = pwd.getpwnam('quant-model')
    except KeyError:
        checked(['useradd', '--system', '--user-group', '--home-dir', '/var/lib/quant-model',
                 '--shell', '/usr/sbin/nologin', 'quant-model'])
        model_user = pwd.getpwnam('quant-model')
    if model_user.pw_uid == 0 or model_user.pw_dir != '/var/lib/quant-model':
        raise ValueError('MODEL_SERVICE_ACCOUNT_NOT_COMPATIBLE')

    model_base = Path('/opt/quant-research-local-model')
    model_base.mkdir(mode=0o755, exist_ok=True)
    archive_rel = Path('assets') / (RUNTIME['sha256'] + '.tar.gz')
    model_rel = Path('models') / MODEL['revision'] / MODEL['file']
    copy_verified(build_home / 'quant-model' / archive_rel, model_base / archive_rel, RUNTIME, verify)
    copy_verified(build_home / 'quant-model' / model_rel, model_base / model_rel, MODEL, verify, magic=b'GGUF')
    assets = stage(model_base, include_model=True)
    for root, directories, files in os.walk(model_base / 'runtimes'):
        os.chmod(root, 0o755)
        for name in files:
            path = Path(root) / name
            if not path.is_symlink():
                os.chmod(path, 0o755 if path == Path(assets['runtime']['binary']) else 0o644)
    for path in (model_base / 'models', model_base / 'models' / MODEL['revision']):
        os.chmod(path, 0o755)
    os.chown(model_base / model_rel, 0, model_user.pw_gid)
    os.chmod(model_base / model_rel, 0o640)

    # Native repository-scoped SSH deploy key. HTTPS Git URLs are transparently
    # transported over GitHub's documented SSH port 443; no token in config/env.
    identity_source = build_home / '.quant-v1-identity/github_ed25519'
    ssh_dir = Path('/var/lib/quant-research/.ssh')
    ssh_dir.mkdir(mode=0o700, exist_ok=True)
    os.chown(ssh_dir, worker.pw_uid, worker.pw_gid)
    key = ssh_dir / 'github_ed25519'
    if not key.exists():
        fd = os.open(identity_source, os.O_RDONLY | os.O_NOFOLLOW)
        with os.fdopen(fd, 'rb') as stream:
            private = stream.read(16385)
        if len(private) > 16384:
            raise ValueError('UNEXPECTED_PRIVATE_KEY_SIZE')
        write_atomic(key, private, 0o600, uid=worker.pw_uid, gid=worker.pw_gid)
    public = checked(['ssh-keygen', '-y', '-f', str(key)])
    with urllib.request.urlopen('https://api.github.com/meta', timeout=20) as response:
        raw_meta = response.read(2 * 1024 * 1024 + 1)
    if len(raw_meta) > 2 * 1024 * 1024:
        raise ValueError('OFFICIAL_GITHUB_METADATA_TOO_LARGE')
    meta = json.loads(raw_meta)
    host_keys = [k for k in meta.get('ssh_keys', []) if k.startswith('ssh-ed25519 ')]
    if not host_keys or any('\n' in key for key in host_keys):
        raise ValueError('OFFICIAL_GITHUB_HOST_KEYS_MISSING')
    known_hosts = '\n'.join('[ssh.github.com]:443 ' + k for k in host_keys) + '\n'
    write_atomic(ssh_dir / 'known_hosts', known_hosts.encode(), 0o600, uid=worker.pw_uid, gid=worker.pw_gid)
    ssh_command = ('/usr/bin/ssh -F /dev/null -i ' + str(key) + ' -o IdentitiesOnly=yes '
                   '-o BatchMode=yes -o StrictHostKeyChecking=yes -o ConnectTimeout=15 '
                   '-o UserKnownHostsFile=' + str(ssh_dir / 'known_hosts'))
    for name, value in (('url.ssh://git@ssh.github.com:443/.insteadOf', 'https://github.com/'),
                        ('core.sshCommand', ssh_command)):
        checked(['runuser', '-u', 'quant-research', '--', 'env', 'HOME=/var/lib/quant-research',
                 'git', 'config', '--global', name, value])
    os.chmod('/var/lib/quant-research/.gitconfig', 0o600)

    # Local model service is allowed before worker activation, and is restarted
    # on boot. The research timer stays absent/stopped until its own canary gates.
    import shlex
    command = shlex.join(server_command(assets))
    unit = f'''[Unit]
Description=Quant V1 local GPT-OSS CPU backend
After=network.target
StartLimitIntervalSec=300
StartLimitBurst=3

[Service]
Type=exec
User=quant-model
Group=quant-model
WorkingDirectory=/opt/quant-research-local-model
ExecStart={command}
Restart=on-failure
RestartSec=15
TimeoutStopSec=30
MemoryMax=10G
MemorySwapMax=0
CPUQuota=180%
TasksMax=64
UMask=0077
StandardOutput=journal
StandardError=journal
LogRateLimitIntervalSec=1h
LogRateLimitBurst=120
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true
PrivateDevices=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictSUIDSGID=true
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6

[Install]
WantedBy=multi-user.target
'''
    write_atomic(Path('/etc/systemd/system/quant-local-model.service'), unit.encode())
    checked(['systemd-analyze', 'verify', '/etc/systemd/system/quant-local-model.service'])
    checked(['systemctl', 'daemon-reload'])
    checked(['systemctl', 'enable', '--now', 'quant-local-model.service'])

    libexec = Path('/usr/local/libexec')
    libexec.mkdir(mode=0o755, exist_ok=True)
    write_atomic(libexec / 'quant-v1-qualify', wrapper(release, 'deploy.oracle_h24_canary',
                 ['--config', '/etc/quant-research/worker.json', '--output', '/var/lib/quant-research/qualification.json'],
                 service_user=True), 0o755)
    write_atomic(libexec / 'quant-v1-activate', wrapper(release, 'deploy.oracle_scheduler_install',
                 ['--release', str(release), '--config', '/etc/quant-research/worker.json',
                  '--qualification', '/var/lib/quant-research/qualification.json', '--activate']), 0o755)
    sudoers = (b'ocarun ALL=(quant-research) NOPASSWD: /usr/local/libexec/quant-v1-qualify ""\n'
               b'ocarun ALL=(root) NOPASSWD: /usr/local/libexec/quant-v1-activate ""\n')
    with tempfile.NamedTemporaryFile() as test:
        test.write(sudoers)
        test.flush()
        checked(['visudo', '-cf', test.name])
    write_atomic(Path('/etc/sudoers.d/quant-v1-bounded-recovery'), sudoers, 0o440)
    # The original identity is retired only after the native worker copy exists.
    if identity_source.exists():
        identity_source.unlink()
    return {'status': 'HOST_PREPARED_TIMER_NOT_ACTIVATED', 'release_sha': sha,
            'model_service': checked(['systemctl', 'is-active', 'quant-local-model.service']),
            'github_public_key': public, 'private_key_exported': False,
            'delegation': 'TWO_FIXED_NO_ARGUMENT_COMMANDS_ONLY; NO_GENERAL_SUDO',
            'required_next': 'Real GitHub claim/recovery canary, gated activation, automatic wakes and restart proof.'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sha', required=True)
    parser.add_argument('--ci-run', required=True, type=int)
    args = parser.parse_args()
